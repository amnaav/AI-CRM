def generate_excel_response(report_title, headers, rows, filename_base, request=None, applied_filters=None):
    """
    Generates a styled Excel (.xlsx) workbook using OpenPyXL.
    Preserves numeric types, escapes text formulas, caps at EXCEL_MAX_ROWS with truncation notice.
    """
    tz = get_crm_timezone()
    now_str = timezone.now().astimezone(tz).strftime('%Y-%m-%d %H:%M:%S %Z')
    user_str = request.user.get_full_name() or request.user.username if request and request.user.is_authenticated else "System"

    is_truncated = False
    original_count = len(rows)
    if original_count > EXCEL_MAX_ROWS:
        rows = rows[:EXCEL_MAX_ROWS]
        is_truncated = True

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = sanitize_filename(report_title)[:30]
    ws.views.sheetView[0].showGridLines = True

    # Styling definitions
    navy_fill = PatternFill(start_color="1E293B", end_color="1E293B", fill_type="solid")  # Slate-800
    meta_fill = PatternFill(start_color="F8FAFC", end_color="F8FAFC", fill_type="solid")
    warn_fill = PatternFill(start_color="FEF2F2", end_color="FEF2F2", fill_type="solid")

    title_font = Font(name="Arial", size=14, bold=True, color="1E293B")
    meta_font = Font(name="Arial", size=9, italic=True, color="64748B")
    header_font = Font(name="Arial", size=10, bold=True, color="FFFFFF")
    data_font = Font(name="Arial", size=10, color="0F172A")
    warn_font = Font(name="Arial", size=10, bold=True, color="DC2626")

    thin_border = Border(
        left=Side(style='thin', color='E2E8F0'),
        right=Side(style='thin', color='E2E8F0'),
        top=Side(style='thin', color='E2E8F0'),
        bottom=Side(style='thin', color='E2E8F0')
    )

    # 1. Report Title Row
    ws.append([report_title])
    ws.cell(row=1, column=1).font = title_font

    # 2. Metadata Rows
    ws.append([f"Exported At: {now_str} | Generated By: {user_str}"])
    ws.cell(row=2, column=1).font = meta_font

    ws.append([f"Applied Filters: {format_applied_filters(applied_filters)}"])
    ws.cell(row=3, column=1).font = meta_font

    cur_row = 4
    if is_truncated:
        ws.append([f"Notice: Export truncated at maximum limit of {EXCEL_MAX_ROWS:,} rows. (Total in DB: {original_count:,})"])
        cell = ws.cell(row=cur_row, column=1)
        cell.font = warn_font
        cell.fill = warn_fill
        cur_row += 1

    ws.append([])  # Spacer row
    cur_row += 1

    # 3. Table Headers
    ws.append(headers)
    for col_idx in range(1, len(headers) + 1):
        cell = ws.cell(row=cur_row, column=col_idx)
        cell.fill = navy_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center", vertical="center")
        cell.border = thin_border
    ws.row_dimensions[cur_row].height = 24

    # 4. Data Rows
    for row in rows:
        cur_row += 1
        clean_row = []
        for val in row:
            sanitized = sanitize_cell_value(val)
            clean_row.append(sanitized)
        ws.append(clean_row)

        for col_idx, cell_val in enumerate(clean_row, start=1):
            cell = ws.cell(row=cur_row, column=col_idx)
            cell.font = data_font
            cell.border = thin_border

            # Maintain numeric formatting
            if isinstance(cell_val, (int, float, Decimal)):
                if isinstance(cell_val, Decimal) or isinstance(cell_val, float):
                    cell.number_format = '#,##0.00'
                else:
                    cell.number_format = '#,##0'
                cell.alignment = Alignment(horizontal="right")
            elif isinstance(cell_val, (datetime.date, datetime.datetime)):
                cell.number_format = 'yyyy-mm-dd'
                cell.alignment = Alignment(horizontal="center")
            else:
                cell.alignment = Alignment(horizontal="left")

    # 5. Auto Column Widths
    for col in ws.columns:
        max_len = 0
        col_letter = get_column_letter(col[0].column)
        for cell in col:
            # Skip title row from length calculation
            if cell.row < 5:
                continue
            val_str = str(cell.value or "")
            if len(val_str) > max_len:
                max_len = len(val_str)
        ws.column_dimensions[col_letter].width = max(max_len + 4, 12)

    # Save to buffer
    buffer = io.BytesIO()
    wb.save(buffer)
    buffer.seek(0)

    safe_name = f"{sanitize_filename(filename_base)}_{timezone.now().astimezone(tz).strftime('%Y%m%d')}.xlsx"
    response = HttpResponse(
        buffer.getvalue(),
        content_type='application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
    )
    response['Content-Disposition'] = f'attachment; filename="{safe_name}"'

    _log_export_activity(request, report_title, 'excel', len(rows), applied_filters)
    return response


