CSV_MAX_ROWS = 5000
EXCEL_MAX_ROWS = 5000
PDF_MAX_ROWS = 2500


def get_crm_timezone():
    tz_name = getattr(settings, 'TIME_ZONE', 'Asia/Kolkata')
    try:
        return ZoneInfo(tz_name)
    except Exception:
        return timezone.get_current_timezone()


def sanitize_filename(base_name):
    clean = re.sub(r'[^a-zA-Z0-9_\-]', '_', str(base_name).strip())
    clean = re.sub(r'_+', '_', clean).strip('_')
    return clean or "report"


def sanitize_cell_value(val):
    """
    Escapes formula injection in text values while preserving legitimate numbers,
    negative numeric values, dates, and booleans as typed values for Excel and CSV.
    """
    if val is None:
        return ""
    if isinstance(val, (int, float, Decimal, bool, datetime.date, datetime.datetime)):
        return val

    s = str(val)
    if not s:
        return ""

    # Formula characters: =, @, tab, carriage return
    if s[0] in ('=', '@', '\t', '\r'):
        return "'" + s

    # Leading + or -: check if it's a genuine numeric string
    if s[0] in ('+', '-'):
        try:
            Decimal(s)
            return val  # Legitimate number string, keep unescaped
        except (InvalidOperation, ValueError):
            return "'" + s

    return s


def format_applied_filters(applied_filters):
    if not applied_filters or not isinstance(applied_filters, dict):
        return "None (All records)"
    parts = []
    for k, v in applied_filters.items():
        if v is not None and v != "":
            clean_k = str(k).replace('_', ' ').title()
            parts.append(f"{clean_k}: {v}")
    return " | ".join(parts) if parts else "None (All records)"


def _log_export_activity(request, report_title, file_format, row_count, applied_filters):
    username = request.user.username if request and request.user.is_authenticated else "System"
    safe_filters = {
        k: str(v)
        for k, v in (applied_filters or {}).items()
        if k not in {'password', 'token', 'secret', 'idempotency_key'}
    }
    log_activity(
        request=request,
        action=ActivityLog.Action.EXPORT,
        module_name="Reports",
        record_id=sanitize_filename(report_title),
        description=f"Exported {report_title} in {file_format.upper()} format ({row_count} rows)",
        metadata={
            'report_title': report_title,
            'format': file_format.lower(),
            'row_count': row_count,
            'filters': safe_filters,
        }
    )


