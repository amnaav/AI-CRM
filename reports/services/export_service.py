def generate_csv_response(report_title, headers, rows, filename_base, request=None, applied_filters=None):
    """
    Generates an RFC-compliant, UTF-8-SIG CSV response with formula protection.
    Caps at CSV_MAX_ROWS with truncation notice.
    """
    tz = get_crm_timezone()
    now_str = timezone.now().astimezone(tz).strftime('%Y-%m-%d %H:%M:%S %Z')
    user_str = request.user.get_full_name() or request.user.username if request and request.user.is_authenticated else "System"

    is_truncated = False
    original_count = len(rows)
    if original_count > CSV_MAX_ROWS:
        rows = rows[:CSV_MAX_ROWS]
        is_truncated = True

    response = HttpResponse(content_type='text/csv; charset=utf-8-sig')
    safe_name = f"{sanitize_filename(filename_base)}_{timezone.now().astimezone(tz).strftime('%Y%m%d')}.csv"
    response['Content-Disposition'] = f'attachment; filename="{safe_name}"'

    writer = csv.writer(response)

    # Metadata Header Block
    writer.writerow([f"# {report_title}"])
    writer.writerow([f"# Exported At: {now_str}", f"Generated By: {user_str}"])
    writer.writerow([f"# Applied Filters: {format_applied_filters(applied_filters)}"])
    if is_truncated:
        writer.writerow([f"# Notice: Export truncated at maximum limit of {CSV_MAX_ROWS:,} rows. (Total: {original_count:,})"])
    writer.writerow([])  # blank spacer

    # Table Header
    writer.writerow(headers)

    # Data Rows
    for row in rows:
        clean_row = []
        for cell in row:
            val = sanitize_cell_value(cell)
            if isinstance(val, (Decimal, float, int)):
                clean_row.append(str(val))
            elif isinstance(val, (datetime.date, datetime.datetime)):
                clean_row.append(str(val))
            elif isinstance(val, bool):
                clean_row.append("Yes" if val else "No")
            else:
                clean_row.append(val)
        writer.writerow(clean_row)

    if is_truncated:
        writer.writerow([])
        writer.writerow([f"[Notice: Export truncated at maximum limit of {CSV_MAX_ROWS:,} rows]"])

    _log_export_activity(request, report_title, 'csv', len(rows), applied_filters)
    return response


