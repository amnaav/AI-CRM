class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute and print 'Page X of Y' on headers/footers."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            super().showPage()
        super().save()

    def draw_page_number(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))

        # Footer
        self.drawString(15 * mm, 10 * mm, "Intelligent Enterprise CRM — Confidential Official Report")
        page_str = f"Page {self._pageNumber} of {page_count}"
        # Landscape A4 width is 297mm
        self.drawRightString(282 * mm, 10 * mm, page_str)

        # Thin footer line
        self.setStrokeColor(colors.HexColor("#e2e8f0"))
        self.setLineWidth(0.5)
        self.line(15 * mm, 14 * mm, 282 * mm, 14 * mm)
        self.restoreState()


def generate_pdf_response(report_title, headers, rows, filename_base, request=None, applied_filters=None):
    """
    Generates a professional Landscape PDF response using ReportLab Platypus.
    Wraps text inside Paragraph cells to prevent clipping or layout crashes.
    Caps at PDF_MAX_ROWS with truncation banner.
    """
    tz = get_crm_timezone()
    now_str = timezone.now().astimezone(tz).strftime('%Y-%m-%d %H:%M:%S %Z')
    user_str = request.user.get_full_name() or request.user.username if request and request.user.is_authenticated else "System"

    is_truncated = False
    original_count = len(rows)
    if original_count > PDF_MAX_ROWS:
        rows = rows[:PDF_MAX_ROWS]
        is_truncated = True

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=landscape(A4),
        leftMargin=15 * mm,
        rightMargin=15 * mm,
        topMargin=15 * mm,
        bottomMargin=18 * mm
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=16,
        leading=20,
        textColor=colors.HexColor('#1e293b')
    )

    meta_style = ParagraphStyle(
        'DocMeta',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8,
        leading=11,
        textColor=colors.HexColor('#64748b')
    )

    warn_style = ParagraphStyle(
        'DocWarn',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8,
        leading=11,
        textColor=colors.HexColor('#dc2626')
    )

    th_style = ParagraphStyle(
        'TableHeader',
        fontName='Helvetica-Bold',
        fontSize=8,
        leading=10,
        textColor=colors.white,
        alignment=1  # Centered
    )

    td_style = ParagraphStyle(
        'TableCell',
        fontName='Helvetica',
        fontSize=7.5,
        leading=9.5,
        textColor=colors.HexColor('#0f172a'),
        alignment=0  # Left
    )

    td_num_style = ParagraphStyle(
        'TableCellNum',
        fontName='Helvetica',
        fontSize=7.5,
        leading=9.5,
        textColor=colors.HexColor('#0f172a'),
        alignment=2  # Right
    )

    elements = []

    # Title & Metadata
    elements.append(Paragraph(report_title, title_style))
    elements.append(Spacer(1, 2 * mm))
    elements.append(Paragraph(f"Exported At: <b>{now_str}</b> | Generated By: <b>{user_str}</b>", meta_style))
    elements.append(Paragraph(f"Applied Filters: <b>{format_applied_filters(applied_filters)}</b>", meta_style))

    if is_truncated:
        elements.append(Spacer(1, 2 * mm))
        elements.append(Paragraph(
            f"Notice: Export truncated at maximum limit of {PDF_MAX_ROWS:,} rows. (Total records in database: {original_count:,})",
            warn_style
        ))

    elements.append(Spacer(1, 4 * mm))

    # Prepare Table Data with Paragraph wrapping
    table_data = []

    # Header row
    th_row = [Paragraph(str(h), th_style) for h in headers]
    table_data.append(th_row)

    # Data rows
    for r in rows:
        row_cells = []
        for cell in r:
            sanitized = sanitize_cell_value(cell)
            if isinstance(sanitized, (int, float, Decimal)):
                if isinstance(sanitized, (float, Decimal)):
                    txt = f"{sanitized:,.2f}"
                else:
                    txt = f"{sanitized:,}"
                row_cells.append(Paragraph(txt, td_num_style))
            elif isinstance(sanitized, (datetime.date, datetime.datetime)):
                row_cells.append(Paragraph(str(sanitized), td_style))
            elif isinstance(sanitized, bool):
                row_cells.append(Paragraph("Yes" if sanitized else "No", td_style))
            else:
                row_cells.append(Paragraph(str(sanitized), td_style))
        table_data.append(row_cells)

    # Table Layout
    pdf_table = Table(table_data, repeatRows=1)
    pdf_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#1e293b')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('ALIGN', (0, 0), (-1, 0), 'CENTER'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 4),
        ('TOPPADDING', (0, 0), (-1, 0), 4),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#f8fafc')]),
        ('TOPPADDING', (0, 1), (-1, -1), 3),
        ('BOTTOMPADDING', (0, 1), (-1, -1), 3),
    ]))

    elements.append(pdf_table)

    # Build PDF with dynamic page numbering canvas
    doc.build(elements, canvasmaker=NumberedCanvas)

    buffer.seek(0)
    safe_name = f"{sanitize_filename(filename_base)}_{timezone.now().astimezone(tz).strftime('%Y%m%d')}.pdf"
    response = HttpResponse(buffer.getvalue(), content_type='application/pdf')
    response['Content-Disposition'] = f'attachment; filename="{safe_name}"'

    _log_export_activity(request, report_title, 'pdf', len(rows), applied_filters)
    return response
